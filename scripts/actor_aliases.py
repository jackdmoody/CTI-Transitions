"""Write configs/actor_aliases.yaml: each actor's ATT&CK group aliases, filling <<ALIASES>> in
prompts/memory_v1.txt (2026-10-27). Read with mitreattack-python from the same pinned ATT&CK
bundle as the ATTK priors (configs/baseline_priors.yaml attack_version; sha256-checked by
ctit.map.attack). The actor's own name is left out of its alias list.

    python scripts/actor_aliases.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import yaml
from mitreattack.stix20 import MitreAttackData

from ctit.cti import manifest
from ctit.map import attack

REPO_ROOT = Path(__file__).resolve().parents[1]
OUT = REPO_ROOT / "configs" / "actor_aliases.yaml"


def aliases(version: str) -> dict:
    attack._bundle(version)  # verifies the pinned sha256
    data = MitreAttackData(str(attack.STIX_DIR / f"enterprise-attack-{version}.json"))
    out = {}
    for actor, info in manifest.load_actors().items():
        g = data.get_object_by_attack_id(info["attack_group"], "intrusion-set")
        out[actor] = {"attack_group": info["attack_group"], "attack_name": g["name"],
                      "aliases": [a for a in g.get("aliases", []) if a != actor]}
    return out


def main() -> int:
    version = yaml.safe_load((REPO_ROOT / "configs" / "baseline_priors.yaml").read_text())["attack_version"]
    body = yaml.safe_dump({"attack_version": version, "actors": aliases(version)}, sort_keys=False, allow_unicode=True)
    OUT.write_text("# Generated by scripts/actor_aliases.py: ATT&CK group aliases for <<ALIASES>> in\n"
                   "# prompts/memory_v1.txt (spec §4.6). Same ATT&CK version as the ATTK priors.\n" + body)
    print(OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
