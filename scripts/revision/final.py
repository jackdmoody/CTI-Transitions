def claims(sc: dict) -> dict:
    t2, t3, rb, at, pig = sc["t2"], sc["t3"], sc["rb"], sc["attr"], sc.get("paired_ig")
    c: dict = {}
    c["GT edges"] = {a: sc["reference"][a]["edges"] for a in A}
    c["L"] = {a: sc["reference"][a]["L"] for a in A}
    for fam in R.FAMILIES:
        c[f"T2 {fam}"] = {a: [round(t2[fam][a]["edge_f1"], 3), None if t2[fam][a]["f1_over_chance"] is None else
                              round(t2[fam][a]["f1_over_chance"], 2), round(t2[fam][a]["percentile"], 1)] for a in A}
    for lab in ("F", "G"):
        r = [t2[f"R-{lab}"][a]["f1_over_chance"] for a in A]
        c[f"R-{lab} ratio range"] = [round(min(r), 2), round(max(r), 2)]
        c[f"R-{lab} min percentile"] = round(min(t2[f"R-{lab}"][a]["percentile"] for a in A), 2)
    for lab in ("Q", "M", "M3"):
        c[f"R-{lab} below 95th"] = {a: round(t2[f"R-{lab}"][a]["percentile"], 1) for a in A if t2[f"R-{lab}"][a]["percentile"] < 95}
        c[f"R-{lab} ratio<1"] = [a for a in A if (t2[f"R-{lab}"][a]["f1_over_chance"] or 0) < 1]
    c["ATTK ratio range"] = [round(min(t2["ATTK"][a]["f1_over_chance"] for a in A), 2),
                             round(max(t2["ATTK"][a]["f1_over_chance"] for a in A), 2)]
    for fam in R.FAMILIES:
        c[f"T3 {fam}"] = {a: [round(t3[fam][a]["point"], 2), t3[fam][a]["iid"]["status"], bool(t3[fam][a]["mark"])] for a in A}
        c[f"T3 {fam} clear above"] = [a for a in A if t3[fam][a]["iid"]["status"] == "above"]
        c[f"T3 {fam} clear below"] = [a for a in A if t3[fam][a]["iid"]["status"] == "below"]
        c[f"T3 {fam} bits>0"] = [a for a in A if t3[fam][a]["point"] > 0]
        c[f"Attr {fam}"] = [at[fam]["n"], {p: q for p, q in at[fam]["plan_to"].items() if p != q}]
    c["T3 marks"] = sorted(f"{fam} {a}" for fam in R.FAMILIES for a in A if t3[fam][a]["mark"])
    for lab in R.PAIRS:
        for key, d in (("edge_f1", 3), ("f1_over_chance", 2), ("ig_bits", 2)):
            c[f"T5 {lab} {key}"] = {a: [None if rb[lab][a][key]["R_minus_B"]["point"] is None else round(rb[lab][a][key]["R_minus_B"]["point"], d),
                                        [round(x, d) for x in rb[lab][a][key]["R_minus_B"]["ci95"]] if rb[lab][a][key]["R_minus_B"]["ci95"] else None,
                                        [round(x, d) for x in rb[lab][a][key]["R_minus_B"]["jackknife"]["ci95"]] if rb[lab][a][key]["R_minus_B"]["jackknife"]["ci95"] else None,
                                        rb[lab][a][key]["R_minus_B"]["clear"]] for a in A}
        mp = rb[lab]["menuPass"]["f1_over_chance"]["R_minus_B"]["jackknife"]
        c[f"T5 {lab} menuPass LOO range"] = None if mp["min"] is None else [round(mp["min"], 2), round(mp["max"], 2)]
        pts = [rb[lab][a]["f1_over_chance"]["R_minus_B"]["point"] for a in A]
        if all(p is not None for p in pts):
            from scipy.stats import spearmanr
            c[f"H2b rho {lab}"] = round(float(spearmanr(pts, [-REFS[a] for a in A]).statistic), 1)
        if pig:
            c[f"paired IG {lab}"] = {a: [round(pig[lab][a]["point"], 2), [round(x, 2) for x in pig[lab][a]["iid"]["ci95"]],
                                         {b: [round(x, 2) for x in pig[lab][a][f"block_{b}"]["ci95"]] for b in B},
                                         pig[lab][a]["iid"]["status"], [pig[lab][a][f"block_{b}"]["status"] for b in B]]
                                     for a in A}
    for lab in ("Q", "M", "M3", "G"):
        c[f"H3 {lab}"] = [{a: round(100 * sc["h3"][lab]["share"][a]) for a in A}, sc["h3"][lab]["meets_80"]]
    c["R/B edges (F,Q,M)"] = [round(min(t2[f"R-{x}"][a]["edges_mean"] / t2[f"B-{x}"][a]["edges_mean"] for x in "FQM" for a in A), 3),
                              round(max(t2[f"R-{x}"][a]["edges_mean"] / t2[f"B-{x}"][a]["edges_mean"] for x in "FQM" for a in A), 3)]
    c["R/B edges (G)"] = [round(min(t2["R-G"][a]["edges_mean"] / t2["B-G"][a]["edges_mean"] for a in A), 3),
                          round(max(t2["R-G"][a]["edges_mean"] / t2["B-G"][a]["edges_mean"] for a in A), 3)]
    c["B-F menuPass recall, edges"] = [round(100 * t2["B-F"]["menuPass"]["recall"]), round(t2["B-F"]["menuPass"]["edges_mean"], 1)]
    return c


def provenance() -> dict:
    sha = subprocess.run(["git", "-C", str(REPO), "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
    dirty = bool(subprocess.run(["git", "-C", str(REPO), "status", "--porcelain", "--untracked-files=no"],
                                capture_output=True, text=True).stdout.strip())
    return {"git_sha": sha, "git_dirty": dirty}


def main() -> int:
    cfg = yaml.safe_load((REPO / "configs" / "v2_priors.yaml").read_text())
    (OUT / "scenarios").mkdir(parents=True, exist_ok=True)
    scs = {}
    tables_only = "--tables-only" in sys.argv[1:]  # rebuild tables from the saved scenarios (no rescoring)
    for key, (variant, filt) in SCENARIOS.items():
        f = OUT / "scenarios" / f"{key}.json"
        if tables_only:
            scs[key] = json.loads(f.read_text())
            continue
        scs[key] = R.scorecard(cfg, variant, filt)
        f.write_text(json.dumps(scs[key], indent=1, default=float))
        print("scored", key, flush=True)
    draft = json.loads((REPO / "results" / "revision" / "sensitivity" / "base.json").read_text())
    main_tables(scs["adopted"])
    extra = supplement(scs, draft, cfg)
    cl = {k: claims(v) for k, v in scs.items()}
    (OUT / "claims.json").write_text(json.dumps(cl, indent=1, default=str))
    (OUT / "phase3.json").write_text(json.dumps(extra, indent=1, default=float))
    (OUT / ("config_tables.yaml" if tables_only else "config.yaml")).write_text(yaml.safe_dump({
        "script": "scripts/revision/final.py", **provenance(), "tables_only": tables_only, "settings": R.SETTINGS, "priors": cfg["priors"],
        "scenarios": {k: {"variant": v, "filter": f} for k, (v, f) in SCENARIOS.items()},
        "seeds": [R.SEED], "draft_record": "results/revision/sensitivity/base.json (c701c77)",
        "old_block_run": str(OLD_BLOCK_RUN.relative_to(REPO))}, sort_keys=False))
    print("case B:", extra["case_b"])
    return 0


