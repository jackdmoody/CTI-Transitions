"""Paper and supplement tables v2, CSV and LaTeX (POST HOC packaging, 2026-10-31; Jack's final coding
pass, items 1-5 and 8, and Phase 3). No model calls.

Models come from the config (`priors`, via configs/v2_priors.yaml), so a model is added by config.
Computed here from the saved priors (one shared chance draw, as paper table a):
  t2_support_recovery         edge-F1, precision, recall, edges, F1/chance, percentile per prior and actor,
                              all-platform ground truth (Table 2) and Windows-only (supplement)
  t4_h4_f1_matrix             4x4 edge-F1 per R label; h4_tests: row-wise (pre-registered: mean over samples
                              of diagonal minus best off-diagonal) and column-wise (post hoc) pass counts
  s_h4_jsd                    4x4 JSD per R label at each alpha in `jsd_alphas`
  s_h4_f1_over_chance         4x4 chance-normalized edge-F1 per R label (shared draw)
Read from the source runs (each must be from a clean commit at or after `min_commit`):
  t3_reading_vs_memory        R - B in F1/chance and IG bits with report-level 95% intervals (reading_bootstrap);
                              h2b: rank correlation of the F1/chance gap with the reference count, both signs
  t5_information_gain         own-plan IG with i.i.d. and block intervals (ig_dependence), attribution counts
                              (prior_likelihood); s_ig_matrix: full IG matrices at every alpha
  t_fabricated_evidence       strict and fragment-aware failing-span rates (extraction_report)
  t_case_a                    every Table 5 prior vs. the executed OTRF APT29 sequence (case_a_v2)
  t_case_b_scripted           case B collapsed, scripted hosts dropped / scripted rules removed (case_b_scripted)
"""
