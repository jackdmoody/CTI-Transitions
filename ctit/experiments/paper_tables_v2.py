def _fmt(v):
    return round(v, 4) if isinstance(v, float) else v


def write(out_dir: Path, name: str, rows: list[dict], caption: str) -> int:
    """<name>.csv and <name>.tex (booktabs tabular, every column, values as in the CSV)."""
    cols = list(dict.fromkeys(k for r in rows for k in r))
    with (out_dir / f"{name}.csv").open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols)
        w.writeheader()
        w.writerows({k: _fmt(v) for k, v in r.items()} for r in rows)
    esc = lambda s: str(s).replace("_", r"\_").replace("&", r"\&").replace("%", r"\%")
    cell = lambda v: "" if v is None else (f"{v:.3f}" if isinstance(v, float) else esc(v))
    tex = [f"% {caption} (POST HOC packaging, 2026-10-31; generated by ctit.experiments.paper_tables_v2)",
           r"\begin{tabular}{@{}" + "l" * len(cols) + r"@{}}", r"\toprule",
           " & ".join(esc(c) for c in cols) + r" \\", r"\midrule"]
    tex += [" & ".join(cell(r.get(c)) for c in cols) + r" \\" for r in rows]
    tex += [r"\bottomrule", r"\end{tabular}", ""]
    (out_dir / f"{name}.tex").write_text("\n".join(tex))
    return len(rows)


# ----------------------------------------------------------------------------- computed from priors

def support_recovery(config: dict, order: np.ndarray, platforms: str) -> list[dict]:
    rows = []
    for a in config["actors"]:
        G = recovery.ground_truth_counts(a, all_platforms=(platforms == "all"))
        ch = v2.ChanceTable(G, order)
        for name in config["families_t2"]:
            Cs = v2.family_counts(config, name, a)
            if not Cs:
                continue
            rs = [recovery.edge_prf(C, G) for C in Cs]
            ratios = [ch.ratio(r["f1"], r["edges_extracted"]) for r in rs]
            m = lambda k: float(np.mean([r[k] for r in rs]))
            rows.append({"ground_truth": platforms, "prior": name, "actor": a, "samples": len(Cs), "truth_edges": ch.g,
                         "edges_mean": m("edges_extracted"), "edge_f1": m("f1"),
                         "edge_f1_sd": float(np.std([r["f1"] for r in rs], ddof=1)) if len(rs) > 1 else 0.0,
                         "precision": m("precision"), "recall": m("recall"),
                         "chance_f1_mean": float(np.mean([ch.mean[r["edges_extracted"]] for r in rs])),
                         "f1_over_chance": (float(np.mean([x for x in ratios if x is not None]))
                                            if any(x is not None for x in ratios) else None),
                         "percentile": float(np.mean([ch.percentile(r["f1"], r["edges_extracted"]) for r in rs]))})
    return rows


def h4(config: dict, order: np.ndarray) -> tuple[list, list, list, list]:
    actors = config["actors"]
    G = {a: recovery.ground_truth_counts(a, all_platforms=True) for a in actors}
    chance = {a: v2.ChanceTable(G[a], order) for a in actors}
    f1_rows, tests, jsd_rows, ratio_rows = [], [], [], []
    for label in config["h4_labels"]:
        Cs = {a: v2.family_counts(config, f"R-{label}", a) for a in actors}
        if not all(Cs.values()):
            continue
        n = len(Cs[actors[0]])
        per = np.array([[[recovery.edge_prf(Cs[ra][s], G[ca])["f1"] for ca in actors] for ra in actors] for s in range(n)])
        M = per.mean(axis=0)
        row_margin = [float(np.mean([per[s, i, i] - max(per[s, i, j] for j in range(len(actors)) if j != i)
                                     for s in range(n)])) for i in range(len(actors))]
        col_margin = [float(M[j, j] - max(M[i, j] for i in range(len(actors)) if i != j)) for j in range(len(actors))]
        for i, ra in enumerate(actors):
            f1_rows.append({"prior": f"R-{label}", "prior_actor": ra, **{f"plan_{ca}": float(M[i, j]) for j, ca in enumerate(actors)},
                            "row_margin": row_margin[i]})
        tests.append({"prior": f"R-{label}", "samples": n,
                      "rowwise_pass": sum(m > 0 for m in row_margin), "colwise_pass": sum(m > 0 for m in col_margin),
                      "rows": len(actors),
                      **{f"row_margin_{a}": row_margin[i] for i, a in enumerate(actors)},
                      **{f"col_margin_{a}": col_margin[i] for i, a in enumerate(actors)}})
        for al in config["jsd_alphas"]:
            J = np.mean([[[recovery.jsd(Cs[ra][s], G[ca], al) for ca in actors] for ra in actors] for s in range(n)], axis=0)
            for i, ra in enumerate(actors):
                margin = min(J[i, j] for j in range(len(actors)) if j != i) - J[i, i]
                jsd_rows.append({"prior": f"R-{label}", "alpha": al, "prior_actor": ra,
                                 **{f"plan_{ca}": float(J[i, j]) for j, ca in enumerate(actors)}, "row_margin": float(margin)})
        for i, ra in enumerate(actors):
            r = {}
            for ca in actors:
                vals = [chance[ca].ratio(*v2.f1_k(C, G[ca])) for C in Cs[ra]]
                r[f"plan_{ca}"] = float(np.mean([x if x is not None else 0.0 for x in vals]))
            ratio_rows.append({"prior": f"R-{label}", "prior_actor": ra, **r,
                               "row_margin": r[f"plan_{ra}"] - max(r[f"plan_{c}"] for c in actors if c != ra)})
    return f1_rows, tests, jsd_rows, ratio_rows


# ----------------------------------------------------------------------------- read from sources

def reading(m: dict, actors: list[str]) -> tuple[list, list]:
    groups = {a: v["attack_group"] for a, v in load_actors().items()}
    refs = {a: reference_count(groups[a]) for a in actors}
    rows, h2b = [], []
    ranks = lambda xs: np.argsort(np.argsort(xs))
    for label, by_a in m["results"].items():
        gaps = {}
        for a in actors:
            r = by_a[a]
            f, i = r["f1_over_chance"], r["ig_bits"]
            ci = lambda d: d["ci95"] or [None, None]
            rows.append({"model": label, "actor": a, "attack_references": refs[a],
                         "r_samples": r["r_samples"], "b_samples": r["b_samples"], "b_held_fixed": r["b_held_fixed"],
                         "R_f1_over_chance": f["R"]["point"], "B_f1_over_chance": f["B"]["point"],
                         "gap_f1_over_chance": f["R_minus_B"]["point"],
                         "gap_lo": ci(f["R_minus_B"])[0], "gap_hi": ci(f["R_minus_B"])[1],
                         "gap_status": v2.status(*f["R_minus_B"]["ci95"]) if f["R_minus_B"]["ci95"] else None,
                         "gap_undefined_resamples": f["R_minus_B"]["undefined_resamples"],
                         "R_ig_bits": i["R"]["point"], "B_ig_bits": i["B"]["point"], "gap_ig_bits": i["R_minus_B"]["point"],
                         "gap_ig_lo": i["R_minus_B"]["ci95"][0], "gap_ig_hi": i["R_minus_B"]["ci95"][1],
                         "gap_ig_status": v2.status(*i["R_minus_B"]["ci95"])})
            gaps[a] = f["R_minus_B"]["point"]
        if all(g is not None for g in gaps.values()):
            g = [gaps[a] for a in actors]
            rho = float(np.corrcoef(ranks(g), ranks([refs[a] for a in actors]))[0, 1])
            h2b.append({"model": label, "rho_gap_vs_reference_count": rho, "rho_gap_vs_fewer_references": -rho,
                        "supports_h2b_direction": -rho > 0, **{f"gap_{a}": gaps[a] for a in actors}})
        else:
            h2b.append({"model": label, "rho_gap_vs_reference_count": None, "rho_gap_vs_fewer_references": None,
                        "supports_h2b_direction": None, **{f"gap_{a}": gaps[a] for a in actors}})
    return rows, h2b


def information_gain(dep: dict, lik: dict, actors: list[str], alpha: str) -> tuple[list, list, list]:
    own = []
    for name, by_a in dep["cells"].items():
        for a in actors:
            c = by_a.get(a)
            if c is None:
                continue
            row = {"prior": name, "actor": a, "alpha": dep["alpha"], "bits": c["bits"], "samples": c["samples"],
                   "iid_lo": c["iid"]["ci95"][0], "iid_hi": c["iid"]["ci95"][1], "iid_status": c["iid"]["status"]}
            for b in dep["block"]["lengths"]:
                k = f"block_{b}"
                row |= {f"{k}_lo": c[k]["ci95"][0], f"{k}_hi": c[k]["ci95"][1], f"{k}_status": c[k]["status"]}
            row["status_changes_at_block"] = " ".join(map(str, c["status_changes_at_block"]))
            own.append(row)
    attr = []
    for name, best in lik["column_best"][alpha].items():
        attr.append({"prior": name, "alpha": float(alpha), "plans_own_actor_best": sum(best[c] == c for c in actors),
                     **{f"plan_{c}_best_prior": best[c] for c in actors}})
    mat = []
    for al, by_name in lik["matrix"].items():
        for name, M in by_name.items():
            for ra in actors:
                mat.append({"prior": name, "alpha": float(al), "prior_actor": ra, **{f"plan_{ca}": M[ra][ca] for ca in actors}})
    return own, attr, mat


def fabricated(m: dict, models: dict[str, str], actors: list[str]) -> list[dict]:
    rows = []
    for label, mode in models.items():
        if mode not in m["modes"]:
            continue
        for a in actors:
            e = m["modes"][mode][f"R/{a}"]
            sm, smp = e["summary"], e["samples"]
            rows.append({"model": label, "actor": a, "samples": len(smp),
                         "transitions_mean": float(np.mean([v["transitions"] for v in smp.values()])),
                         "strict": sm["hallucinated_strict"]["mean"], "strict_sd": sm["hallucinated_strict"]["sd"],
                         "fragment_aware": sm["hallucinated_fragments"]["mean"],
                         "fragment_aware_sd": sm["hallucinated_fragments"]["sd"]})
    return rows


def case_a(m: dict) -> list[dict]:
    return [{"prior": name, "prior_actor": a, "samples": c["samples"], "bits": c["bits"], "ci95_lo": c["ci95"][0],
             "ci95_hi": c["ci95"][1], "status": c["status"], "edges": c["edges"], "edge_f1": c["edge_f1"],
             "f1_over_chance": c["f1_over_chance"], "percentile": c["percentile"]}
            for name, by_a in m["cells"].items() for a, c in by_a.items()]


def case_b(m: dict) -> list[dict]:
    rows = []
    for variant in ("i_drop_xx01_xx51_hosts", "ii_drop_scripted_rule_tags"):
        v = m[variant]
        for c, e in v["conditions"].items():
            p, ci = e["point"], e["ci95"]
            rows.append({"variant": variant, "windows": v["windows"], "positive": v["positive"], "condition": c,
                         "samples": e["samples"], "auprc": p["auprc"], "auprc_lo": ci["auprc"][0], "auprc_hi": ci["auprc"][1],
                         "auroc": p["auroc"], "auroc_lo": ci["auroc"][0], "auroc_hi": ci["auroc"][1],
                         "det_1fpr": p["det_1fpr"], "det_1fpr_lo": ci["det_1fpr"][0], "det_1fpr_hi": ci["det_1fpr"][1]})
    return rows


def run(config: dict, calls=None) -> dict:
    src = {k: _source(v, config["min_commit"]) for k, v in config["sources"].items()}
    out_dir = REPO_ROOT / config["out_dir"]
    out_dir.mkdir(parents=True, exist_ok=True)
    actors = config["actors"]
    order = v2.shared_chance(config)
    f1m, tests, jsd, ratio = h4(config, order)
    read, h2b = reading(src["reading"], actors)
    own, attr, igmat = information_gain(src["ig_dependence"], src["likelihood"], actors, str(config["alpha"]))
    tables = {
        "t2_support_recovery": (support_recovery(config, order, "all"),
            "Table 2: edge-F1, precision, recall, F1/chance (shared draw) and percentile, all-platform ground truth"),
        "s_support_recovery_windows": (support_recovery(config, order, "windows"),
            "Supplement: the same against the Windows-only ground truth"),
        "t3_reading_vs_memory": (read, "Table 3: R - B in F1/chance and own-plan IG bits, report-level bootstrap 95% intervals"),
        "t3_h2b": (h2b, "H2b: rank correlation of the R - B F1/chance gap with the ATT&CK reference count, both signs"),
        "t4_h4_f1_matrix": (f1m, "Table 4: H4 edge-F1 matrices (prior actor x plan actor), mean over samples"),
        "t4_h4_tests": (tests, "H4 row-wise (pre-registered) and column-wise (post hoc) pass counts and margins"),
        "s_h4_jsd": (jsd, "Supplement: H4 JSD matrices at alpha in jsd_alphas"),
        "s_h4_f1_over_chance": (ratio, "Supplement: H4 chance-normalized edge-F1 matrices (shared draw)"),
        "t5_information_gain": (own, "Table 5: own-plan IG bits with i.i.d. and circular block bootstrap intervals"),
        "t5_attribution": (attr, "Attribution: plans whose highest-likelihood prior is their own actor's"),
        "s_ig_matrix": (igmat, "Supplement: full IG matrices (prior actor x plan actor) at every alpha"),
        "t_fabricated_evidence": (fabricated(src["extraction"], config["fabricated_modes"], actors),
            "Failing-evidence rates of R priors, strict and fragment-aware"),
        "t_case_a": (case_a(src["case_a"]), "Case A: every Table 5 prior vs. the executed OTRF APT29 sequence"),
        "t_case_b_scripted": (case_b(src["case_b_scripted"]),
            "Case B collapsed, scripted hosts dropped and scripted rules removed, host-cluster 95% intervals"),
    }
    counts = {name: write(out_dir, name, rows, desc) for name, (rows, desc) in tables.items()}
    readme = ["# Paper tables v2 (POST HOC packaging, 2026-10-31)", "",
              "Everything here is post hoc (Jack's final coding pass, 2026-10-31). Each table is a CSV and a LaTeX "
              "tabular with the same columns.", "",
              f"Sources (clean commits at or after {config['min_commit']}): "
              + ", ".join(f"{k} `{v}`" for k, v in config["sources"].items()) + ".",
              "Priors: " + ", ".join(f"{k} `{v['run']}/{v['mode']}`" for k, v in config["priors"].items()) + ".", ""]
    readme += [f"- `{name}`: {desc}." for name, (_, desc) in tables.items()]
    (out_dir / "README.md").write_text("\n".join(readme) + "\n")
    return {"note": "POST HOC packaging (2026-10-31): paper tables v2", "out_dir": config["out_dir"],
            "sources": config["sources"], "rows": counts}
