# ----------------------------------------------------------------------------- formatting

def sg(x, d=2, lead=False):
    """Signed number; lead=False drops the leading zero (+.11), as the draft prints Table 3."""
    if x is None:
        return "—"
    s = f"{x:+.{d}f}"
    return s if lead else s.replace("+0.", "+.").replace("-0.", "-.")


def iv(c, d=2):
    return "—" if not c else f"[{c[0]:+.{d}f}, {c[1]:+.{d}f}]"


def tex_num(s: str) -> str:
    return s.replace("−", "-").replace("+", "$+$").replace("-", "$-$") if s not in ("—",) else "---"


def write(dirn: Path, name: str, header: list[str], rows: list[list], caption: str) -> None:
    dirn.mkdir(parents=True, exist_ok=True)
    with (dirn / f"{name}.csv").open("w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(header)
        w.writerows(rows)
    esc = lambda s: str(s).replace("&", r"\&").replace("%", r"\%").replace("_", r"\_").replace("→", r"$\to$") \
        .replace("−", "$-$").replace("÷", r"$\div$").replace("≥", r"$\geq$").replace("Δ", r"$\Delta$")
    lines = [f"% {caption}", r"\begin{tabular}{@{}" + "ll" + "r" * (len(header) - 2) + "@{}}", r"\toprule",
             " & ".join(esc(h) for h in header) + r" \\", r"\midrule"]
    lines += [" & ".join(esc(c) for c in r) + r" \\" for r in rows]
    lines += [r"\bottomrule", r"\end{tabular}"]
    (dirn / f"{name}.tex").write_text("\n".join(lines) + "\n")


