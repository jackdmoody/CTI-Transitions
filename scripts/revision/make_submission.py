"""Build paper/w2_aics_submission.tex (official AAAI-27 kit) from paper/w2_aics_draft_REVISED_v2.tex. No computation.

    python scripts/revision/make_submission.py [--kit DIR]

The preamble is the kit's CameraReady2027.tex preamble verbatim (AICS is not anonymized), up to and including
\\setcounter{secnumdepth}{0}. Then come the draft's own packages and macros, minus what the kit forbids or replaces:
- no hyperref (forbidden by the kit), and no \\draftnote (a preview-style command);
- no url/graphicx/natbib/booktabs/listings or \\urlstyle lines (the kit preamble already has them);
- no \\bibliographystyle (aaai2027.sty sets aaai2027 itself; a second one is a BibTeX error).
The body (\\title ... \\end{document}) is copied unchanged otherwise. Compile next to aaai2027.sty/.bst from the kit.
Fails if the draft's preamble has a line this script does not know how to handle.
"""
from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
DRAFT = REPO / "paper" / "w2_aics_draft_REVISED_v2.tex"
OUT = REPO / "paper" / "w2_aics_submission.tex"
KIT_TEMPLATE = "CameraReady2027.tex"

# draft preamble lines that the kit preamble replaces or forbids
DROP = (r"^\\documentclass", r"^\\usepackage\{aaai27-preview\}", r"^\\usepackage\{(url|graphicx|natbib|booktabs|listings|hyperref|comment)\}",
        r"^\\urlstyle", r"^\\def\\UrlFont", r"^\\draftnote", r"^\\lstset", r"^\s+(breakatwhitespace|frame)=")
# draft preamble lines kept (after the kit preamble)
KEEP = (r"^\\usepackage\{amsmath,amssymb\}", r"^\\usepackage\{xcolor\}", r"^\\setlength\{\\emergencystretch\}",
        r"^\\newcommand", r"^\\newif", r"^\\ifdefined")


def kit_preamble(kit: Path) -> str:
    t = (kit / KIT_TEMPLATE).read_text()
    end = t.index("\\setcounter{secnumdepth}{0}")
    return t[: t.index("\n", end) + 1]


def split_draft(src: str) -> tuple[list[str], str]:
    i = src.index("\\title{")
    return src[:i].splitlines(), src[i:]


def build(kit: Path) -> str:
    pre, body = split_draft(DRAFT.read_text())
    kept = []
    for line in pre:
        if not line.strip() or line.lstrip().startswith("%"):
            continue
        if any(re.match(p, line) for p in DROP):
            continue
        if any(re.match(p, line) for p in KEEP):
            kept.append(line)
            continue
        raise ValueError(f"unhandled draft preamble line: {line!r}")
    n = len(re.findall(r"^\\bibliographystyle\{.*$\n?", body, re.M))
    if n != 1:
        raise ValueError(f"expected one \\bibliographystyle in the draft body, found {n}")
    body = re.sub(r"^\\bibliographystyle\{.*$\n?", "", body, flags=re.M)
    for bad in ("\\usepackage{hyperref}", "\\draftnote", "\\href{"):
        if bad in body:
            raise ValueError(f"{bad} in the draft body")
    head = ("%% W2 -- AICS @ AAAI-27 -- submission version for the official AAAI-27 author kit.\n"
            "%% GENERATED by scripts/revision/make_submission.py from paper/w2_aics_draft_REVISED_v2.tex. Do not edit by hand.\n"
            "%% Compile with aaai2027.sty and aaai2027.bst from the kit, references.bib, fig_method.pdf and tables/.\n")
    return head + kit_preamble(kit) + "\n% ---- paper-specific packages and macros (from the draft) ----\n" + "\n".join(kept) + "\n\n" + body


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--kit", default=os.environ.get("AAAI27_KIT"), help="AAAI-27 author kit directory (or $AAAI27_KIT)")
    a = ap.parse_args()
    if not a.kit:
        ap.error("pass --kit or set AAAI27_KIT")
    OUT.write_text(build(Path(a.kit).expanduser()))
    print(OUT.relative_to(REPO))
    return 0


if __name__ == "__main__":
    sys.exit(main())
