def t3_cell(c: dict) -> str:
    s = tex_num(sg(c["point"]))
    if c["iid"]["status"] == "above":
        s = r"\textbf{" + s + "}"
    sup = ("\\dag" if c["iid"]["status"] == "below" else "") + ("*" if c["mark"] else "")
    return s + (r"\textsuperscript{" + sup + "}" if sup else "")


